// data/catalog.json → src/data.generated.ts
// The JSON is embedded as a string and parsed at load time: JSON.parse is faster than evaluating a
// large object literal, and TypeScript only has to check one string instead of 600 objects.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const json = readFileSync(join(root, "data", "catalog.json"), "utf8");
const data = JSON.parse(json); // validates
const src = `// GENERATED by scripts/gen-data.mjs from data/catalog.json. Do not edit.
import type { Catalog } from "./types";

export const CATALOG: Catalog = JSON.parse(${JSON.stringify(JSON.stringify(data))});
`;
writeFileSync(join(root, "src", "data.generated.ts"), src);
console.log(`src/data.generated.ts  ${data.tests.length} tests, ${(src.length / 1024).toFixed(0)} KB`);
